def main():
    cc = shutil.which(os.environ.get("CC", "clang"))
    if not cc:
        raise SystemExit("clang is required")
    symbols = (ROOT / "decomp/config/us/symbols.txt").read_text()
    addr = lambda name: int(re.search(r"^" + name + r"\s*=\s*(0x[0-9A-Fa-f]+)", symbols, re.M)[1], 16)
    assert addr("STDVS_CAMERA") - addr("MAP_COLLISION_DATA") + 36 == 0x2824
    sanitize = ["-fsanitize=address,undefined", "-fno-sanitize-recover=all"] if "--sanitize" in sys.argv else []
    includes = [ROOT / "crates/decomp-c/include", ROOT / "decomp/include",
                ROOT / "decomp/external/psyq_headers/mw_lib41/include"]
    with tempfile.TemporaryDirectory(prefix="dw1-camera-") as tmp:
        tmp = Path(tmp)
        for before, native in [(True, True), (False, True), (False, False)]:
            name = "before-native" if before else "candidate-native" if native else "retail-branch"
            inc = tmp / name
            inc.mkdir()
            header = (includes[0] / "dw1_native.h").read_text()
            (inc / "dw1_native.h").write_text(header)
            source = (ROOT / "decomp/src/main/map_collision.c").read_text()
            macro = source[source.index("#ifdef DW1_NATIVE\n#define DW1_COLLISION_IDX"):source.index("static inline int32_t copyValue")]
            shadow = SOURCE.read_text()
            if before:
                # Mechanically restore only the previous raw query;
                # no dependency on a contributor-local commit, assets, or private history.
                current = "#define DW1_COLLISION_BYTE(i) dw1_collision_byte(i)"
                assert macro.count(current) == 1
                macro = macro.replace(current, "#define DW1_COLLISION_BYTE(i) MAP_COLLISION_DATA[dw1_collision_index(i)]")
            code = PREAMBLE.replace('#include "dw1_native.h"', '#include "dw1_native.h"' + ("" if native else "\n#undef DW1_NATIVE"))
            code += macro
            code += function(source, "int32_t getTileTrigger(VECTOR *pos)")
            code += function(source, "void getModelTile(VECTOR *pos, int16_t *outTileX, int16_t *outTileY)")
            # forward declaration for the real shadow body
            code += shadow + HARNESS
            c, exe = tmp / (name + ".c"), tmp / name / "check"
            c.write_text(code)
            subprocess.run([cc, "-std=gnu99", "-DVERSION_US", "-fwrapv", "-fno-strict-aliasing", "-fno-builtin",
                            *sanitize, "-I" + str(inc), *["-I" + str(i) for i in includes], str(c), "-o", str(exe)], check=True)
            for n in list(range(15)) + list(range(100, 113)):
                fatal = (before and n < 9) or (native and 9 <= n <= 13)
                if n >= 100:
                    fatal = n - 100 not in [1, 2, 3, 4]
                expected = 81 if fatal else 0
                got = subprocess.run([str(exe), str(n)]).returncode
                if got != expected:
                    raise SystemExit(f"FAIL {name} case {n}: {got} != {expected}")
            print(f"PASS {name}: 28 real-function/query/raw-guard scenarios", flush=True)


SOURCE = ROOT / "decomp/src/main/drop_shadow.c"
if __name__ == "__main__":
    main()
