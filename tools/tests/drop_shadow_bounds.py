#!/usr/bin/env python3
"""Compile the real shadow routine with recording GPU calls; no game assets or saves.

Only wholly invisible, unrepresented native collision queries may be elided. In particular,
off-grid is NOT synonymous with unrepresented (the tamer's preceding PS1 span is modelled).
The retained non-native branch must query/draw as before, even for offscreen projections.
Generated by Codex (GPT-6.1 sol).
"""
from pathlib import Path
import os
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "decomp/src/main/drop_shadow.c"
PREAMBLE = r'''
#include "dw1_native.h"
#include <libgpu.h>
#include <libgs.h>
#include <libgte.h>
#include <dw/aabb.h>
#include <dw/entity.h>
#include <dw/params.h>
_Noreturn extern void _Exit(int);
static int queries, projections, links, advances, boxes, trigger;
static uint32_t projection_flags;
static int16_t xy[8];
static POLY_FT4 packet[2];
static GsOT_TAG tags[4096];
static GsOT table;
GsOT *ACTIVE_ORDERING_TABLE = &table;
MATRIX GsWSMATRIX;
DigimonPara DIGIMON_DATA[NUM_DIGIMON];
int32_t DRAWING_OFFSET_X, DRAWING_OFFSET_Y;
_Noreturn void dw1_native_fatal(const char *reason) { _Exit(81); }
PACKET *GsGetWorkBase(void) { return (PACKET *)packet; }
void GsSetWorkBase(PACKET *p) {
    if (p != (PACKET *)(packet+1)) _Exit(82);
    advances++;
}
void SetPolyFT4(POLY_FT4 *p) { setPolyFT4(p); }
void SetSemiTrans(void *p, int on) { setSemiTrans(p,on); }
u_short GetClut(int x,int y) { return (y<<6)|(x>>4); }
void AddPrim(void *ot,void *p) {
    if (ot != tags+0xFFD || p != packet) _Exit(83);
    links++;
}
void setRotTransMatrix(MATRIX *m) { if (m != &GsWSMATRIX) _Exit(84); }
long RotTransPers4(SVECTOR *a,SVECTOR *b,SVECTOR *c,SVECTOR *d,
                  long *s0,long *s1,long *s2,long *s3,long *depth,long *flag) {
    projections++;
    long *out[4]={s0,s1,s2,s3};
    for (int i=0;i<4;i++) *out[i]=(uint16_t)xy[2*i]|((uint32_t)(uint16_t)xy[2*i+1]<<16);
    *depth=0; *flag=projection_flags; return 1;
}
void renderAABB(AABB *box) { boxes++; }
'''

QUERY = r'''
int32_t getTileTrigger(VECTOR *pos) {
    int16_t tx,tz;
    getModelTile(pos,&tx,&tz);
    queries++;
#ifdef DW1_NATIVE
    dw1_collision_index(tx+tz*100);
#endif
    return trigger;
}
'''

HARNESS = r'''
#undef main
#define CHECK(x) do { if (!(x)) return 2; } while (0)
int main(int argc,char **argv) {
    int n=0;
    for (char *s=argv[1]; *s; s++) n=n*10+*s-'0';
    if(n>=1000) { /* strict collision guard itself: unchanged endpoints */
        int32_t values[]={-0xE001,-0xE000,-1,0,0x27FF,0x2800,0x285F,0x7FFFFFFF};
        int i=n-1000;
        CHECK(i>=0 && i<8);
        CHECK(dw1_collision_index(values[i])==values[i]);
        return 0;
    }
    PositionData pos={0};
    Entity entity={0};
    entity.posData=&pos;
    DIGIMON_DATA[0].radius=90;
    DIGIMON_DATA[0].height=200;
    table.org=tags;
    DRAWING_OFFSET_X=160;
    DRAWING_OFFSET_Y=120;
    pos.location.vx=-1416; pos.location.vz=-5376; /* measured failing index 0x285F */
    const int16_t shapes[][8]={
        {-180,-10,-170,-10,-180,10,-170,10}, /* wholly left */
        {170,-10,180,-10,170,10,180,10},     /* right */
        {-10,-140,10,-140,-10,-130,10,-130}, /* above */
        {-10,130,10,130,-10,140,10,140},     /* below */
        {-10,-10,10,-10,-10,10,10,10},       /* visible */
        {-200,-10,200,-10,-200,10,200,10},   /* crosses screen, no corner inside */
        {-200,-200,200,-200,-200,200,200,200}, /* encloses screen */
        {-163,-10,-162,-10,-163,10,-162,10}, /* HD/edge margin */
        {162,-10,163,-10,162,10,163,10},
        {-10,-123,10,-123,-10,-122,10,-122},
        {-10,122,10,122,-10,123,10,123},
        {-170,-10,-163,-10,-170,10,-163,10}, /* one corner reaches margin */
        {-6,1023,125,958,-46,830,73,773},    /* measured post-battle quad */
    };
    int shape=n%13, group=n/13;
    for(int i=0;i<8;i++) xy[i]=shapes[shape][i];
    int represented=0, should_skip=shape<4 || shape==12;
    switch(group) {
        case 0: break;
        case 1: pos.location.vx=0;pos.location.vz=0;represented=1;break;
        case 2: pos.location.vx=-1400;pos.location.vz=5376;represented=1;break;
        case 3: pos.location.vx=0;pos.location.vz=0;represented=1;trigger=-1;break;
        case 4: /* Camera/pan offsets: translate projected positions along with viewport. */
            DRAWING_OFFSET_X=320;DRAWING_OFFSET_Y=44;
            if(shape!=12) for(int i=0;i<4;i++) {xy[2*i]-=160;xy[2*i+1]+=76;}
            projection_flags=0x80003000u; /* SY + depth-cue saturation, measured in repro */
            break;
        case 5: projection_flags=0x01000000u;should_skip=0;break; /* IR1 saturation */
        case 6: projection_flags=0x00800000u;should_skip=0;break; /* IR2 saturation */
        case 7: projection_flags=0x40000000u;should_skip=0;break; /* MAC overflow */
        case 8: projection_flags=0x00040000u;should_skip=0;break; /* depth saturation */
        case 9: DRAWING_OFFSET_X=-900;should_skip=0;break; /* viewport beyond SXY range */
        case 10: pos.location.vx=0;pos.location.vz=65000;break; /* before represented span */
        case 11: pos.location.vx=0;pos.location.vz=62000;represented=1;break;
        case 12: pos.location.vx=0;pos.location.vz=0;represented=1;trigger=2;break;
        default: return 3;
    }
    renderDropShadow(&entity);
#ifdef DW1_NATIVE
    if(!represented) {
        CHECK(should_skip);
        CHECK(queries==0 && projections==1 && links==0 && advances==0 && boxes==0);
        return 0;
    }
#endif
    CHECK(queries==1);
    if(trigger==-1) {
        CHECK(projections==0 && links==0 && advances==0 && boxes==0);
    } else {
        CHECK(projections==1 && links==1 && advances==1 && boxes==1);
        CHECK(packet[0].r0==0x30 && packet[0].g0==0x30 && packet[0].b0==0x30);
        CHECK(packet[0].u0==0x40 && packet[0].v0==0x80);
        CHECK(packet[0].u3==0x7f && packet[0].v3==0xbf);
        CHECK(packet[0].tpage==getTPage(1,2,832,256));
    }
    return 0;
}
'''


def function(source, signature):
    start = source.index(signature)
    # Skip declarations when a function has a prototype as well.
    while source.find(";", start) < source.find("{", start):
        start = source.index(signature, start + len(signature))
    end = source.index("\n}", start) + 2
    return source[start:end]


def main():
    cc = shutil.which(os.environ.get("CC", "clang"))
    if not cc:
        raise SystemExit("clang is required (Xcode Command Line Tools)")
    shadow = SOURCE.read_text()
    tile = function((ROOT / "decomp/src/main/map_collision.c").read_text(),
                    "void getModelTile(")
    includes = [ROOT / "crates/decomp-c/include", ROOT / "decomp/include",
                ROOT / "decomp/external/psyq_headers/mw_lib41/include"]
    with tempfile.TemporaryDirectory(prefix="dw1-shadow-") as folder:
        folder = Path(folder)
        for native in [True, False]:
            name = "native" if native else "retail-branch"
            code = PREAMBLE + ("" if native else "\n#undef DW1_NATIVE\n")
            code += tile + QUERY + shadow + HARNESS
            c, exe = folder / f"{name}.c", folder / name
            c.write_text(code)
            subprocess.run([cc, "-std=gnu99", "-DVERSION_US", "-fwrapv", "-fno-strict-aliasing", "-fno-builtin",
                            *[f"-I{p}" for p in includes], str(c), "-o", str(exe)], check=True)
            for case in range(169):
                group, shape = divmod(case, 13)
                fatal = native and group in [0, 4, 5, 6, 7, 8, 9, 10] and (
                    shape not in [0, 1, 2, 3, 12] or group in [5, 6, 7, 8, 9])
                expected = 81 if fatal else 0
                result = subprocess.run([str(exe), str(case)])
                if result.returncode != expected:
                    raise SystemExit(f"FAIL {name} case {case}: got {result.returncode}, expected {expected}")
            for i in range(8):
                expected = 81 if i in [0, 5, 6, 7] else 0
                result = subprocess.run([str(exe), str(1000+i)])
                if result.returncode != expected:
                    raise SystemExit(f"FAIL strict collision guard boundary {i}")
            print(f"PASS {name}: 169 shadow scenarios + 8 unchanged guard boundaries", flush=True)


if __name__ == "__main__":
    main()
